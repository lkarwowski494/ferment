export type KombuchaBottleType =
  | 'HEAVY_SWING_TOP_AMBER' // Rated up to 4.5 vol CO2 (~3.8 bar)
  | 'CROWN_CAP_BEER_BOTTLE' // Rated up to 3.5 vol CO2 (~2.8 bar)
  | 'CHAMPAGNE_HEAVY'       // Rated up to 6.0 vol CO2
  | 'SQUARE_DECORATIVE';    // Hazardous! Rated max 1.8 vol CO2

export interface FruitJuiceProfile {
  id: string;
  name: string;
  typicalBrixPct: number; // g sugar per 100g
}

export const FRUIT_JUICE_PROFILES: FruitJuiceProfile[] = [
  { id: 'apple', name: 'Sok jabłkowy 100% tłoczony', typicalBrixPct: 11.5 },
  { id: 'raspberry', name: 'Sok malinowy (puree)', typicalBrixPct: 7.5 },
  { id: 'ginger_lemon', name: 'Ekstrakt imbirowo-cytrynowy z miodem', typicalBrixPct: 14.0 },
  { id: 'pomegranate', name: 'Sok z granatu', typicalBrixPct: 13.0 },
  { id: 'pure_cane_sugar', name: 'Cukier trzcinowy (syrop)', typicalBrixPct: 65.0 },
];

export interface Kombucha2FBlendingParams {
  baseKombuchaLiters: number;
  juiceProfileId: string;
  juiceVolumeMl: number;
  bottleType: KombuchaBottleType;
  temperatureC: number;
  daysAtRoomTemp: number;
}

export interface Kombucha2FBlendingResult {
  totalBeverageVolumeLiters: number;
  sugarAddedGrams: number;
  effectiveSugarGramsPerLiter: number;
  estimatedCo2Volumes: number;
  estimatedPressureBarAt20C: number;
  bottlePressureCapacityVol: number;
  isExplosionHazard: boolean;
  alertLevel: 'SAFE' | 'CAUTION_HIGH_PRESSURE' | 'EXPLOSION_HAZARD';
  warningMessage: string;
  refrigerationAdvice: string;
}

/**
 * Calculates CO2 volume and internal pressure generated by fruit juice sugars during 2F.
 */
export function calculateKombucha2FBlending(params: Kombucha2FBlendingParams): Kombucha2FBlendingResult {
  const baseLiters = Math.max(0.5, params.baseKombuchaLiters);
  const juiceMl = Math.max(0, params.juiceVolumeMl);
  const totalVolumeLiters = Math.round((baseLiters + juiceMl / 1000.0) * 100) / 100;

  const juice = FRUIT_JUICE_PROFILES.find((p) => p.id === params.juiceProfileId) || FRUIT_JUICE_PROFILES[0];
  const sugarAddedGrams = Math.round(((juiceMl * juice.typicalBrixPct) / 100.0) * 10) / 10;
  const effectiveSugarGramsPerLiter = Math.round((sugarAddedGrams / totalVolumeLiters) * 10) / 10;

  // In sealed kombucha bottles at 20-23°C:
  // 4 grams of fermentable sugar per liter yields approx 1.0 volume of dissolved CO2
  // Days of fermentation at room temperature: typical active fermentation takes ~3-4 days to convert ~6-10 g sugar
  const days = Math.max(1, Math.min(10, params.daysAtRoomTemp));
  const tempFactor = params.temperatureC >= 25 ? 1.2 : params.temperatureC <= 18 ? 0.7 : 1.0;

  // Sugar fermented over time:
  const potentialCo2FromSugar = (effectiveSugarGramsPerLiter / 4.0) * 0.85;
  const kineticRate = Math.min(1.0, (days * 0.28) * tempFactor);
  const baseDissolvedCo2 = 0.8; // Residual CO2 from 1F

  const calculatedCo2 = baseDissolvedCo2 + potentialCo2FromSugar * kineticRate;
  const estimatedCo2Volumes = Math.round(calculatedCo2 * 10) / 10;

  // Pressure in bars at 20°C: P(bar) ~= (Co2_vol - 0.7) * 0.85
  const estimatedPressureBar = Math.max(0, Math.round((estimatedCo2Volumes * 0.8) * 10) / 10);

  let bottleCapacityVol = 3.5;
  if (params.bottleType === 'HEAVY_SWING_TOP_AMBER') bottleCapacityVol = 4.5;
  else if (params.bottleType === 'CHAMPAGNE_HEAVY') bottleCapacityVol = 6.0;
  else if (params.bottleType === 'SQUARE_DECORATIVE') bottleCapacityVol = 1.8;

  const isExplosionHazard = estimatedCo2Volumes > bottleCapacityVol || params.bottleType === 'SQUARE_DECORATIVE';

  let alertLevel: Kombucha2FBlendingResult['alertLevel'] = 'SAFE';
  let warningMessage = 'Ciśnienie w normie. Bezpieczne nagazowanie.';

  if (params.bottleType === 'SQUARE_DECORATIVE') {
    alertLevel = 'EXPLOSION_HAZARD';
    warningMessage = 'KRYTYCZNE RYZYKO: Butelki kwadratowe/ozdobne nie posiadają odporności ciśnieniowej i pękają przy gwałtownej eksplozji szkła! Używaj wyłącznie okrągłych butelek ciśnieniowych.';
  } else if (isExplosionHazard) {
    alertLevel = 'EXPLOSION_HAZARD';
    warningMessage = `ZAGROŻENIE EKSPLOZJĄ! Szacowane ${estimatedCo2Volumes} vol CO2 przekracza limit butelki (${bottleCapacityVol} vol). Natychmiast schłodź butelkę do 4°C i ostrożnie odgazuj!`;
  } else if (estimatedCo2Volumes > bottleCapacityVol * 0.8) {
    alertLevel = 'CAUTION_HIGH_PRESSURE';
    warningMessage = `Wysokie wysycenie (${estimatedCo2Volumes} vol). Zbliżasz się do limitu butelki. Schłodź butelki w lodówce przed otwarciem.`;
  }

  const refrigerationAdvice = `Po ${days} dniach w ${params.temperatureC}°C przenieś butelki do lodówki (4°C) na min. 12h. Niska temperatura zwiększa rozpuszczalność CO2 w płynie i zapobiega wytryskowi piany (gushing).`;

  return {
    totalBeverageVolumeLiters: totalVolumeLiters,
    sugarAddedGrams,
    effectiveSugarGramsPerLiter,
    estimatedCo2Volumes,
    estimatedPressureBarAt20C: estimatedPressureBar,
    bottlePressureCapacityVol: bottleCapacityVol,
    isExplosionHazard,
    alertLevel,
    warningMessage,
    refrigerationAdvice,
  };
}
