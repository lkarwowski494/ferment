// ============================================================================
// Apps4Brew Studio — FERMENT QR Deep-Link & Barcode Parser Protocol
// Handles ferment://batch/<id>, ferment://wheel/<id>, JSON & offline tags
// ============================================================================

export type QrPayloadType = 'batch' | 'wheel' | 'recipe' | 'unknown';

export interface ParsedQrResult {
  type: QrPayloadType;
  id?: string;
  recipeData?: string;
  raw: string;
}

/**
 * Builds canonical deep-link URI for batch
 */
export function buildBatchDeepLink(batchId: string): string {
  return `ferment://batch/${batchId.trim()}`;
}

/**
 * Builds canonical deep-link URI for cave cheese wheel
 */
export function buildWheelDeepLink(wheelId: string): string {
  return `ferment://wheel/${wheelId.trim()}`;
}

/**
 * Parses any incoming QR code payload, barcode string or deep-link URI
 */
export function parseDeepLinkOrQr(payload: string): ParsedQrResult {
  const trimmed = (payload || '').trim();
  if (!trimmed) {
    return { type: 'unknown', raw: '' };
  }

  // 1. Check ferment:// scheme deep links
  if (trimmed.startsWith('ferment://')) {
    if (trimmed.startsWith('ferment://batch/')) {
      const id = trimmed.replace('ferment://batch/', '').split('?')[0].trim();
      return { type: 'batch', id, raw: trimmed };
    }
    if (trimmed.startsWith('ferment://batch?id=')) {
      const id = trimmed.replace('ferment://batch?id=', '').split('&')[0].trim();
      return { type: 'batch', id, raw: trimmed };
    }
    if (trimmed.startsWith('ferment://wheel/')) {
      const id = trimmed.replace('ferment://wheel/', '').split('?')[0].trim();
      return { type: 'wheel', id, raw: trimmed };
    }
    if (trimmed.startsWith('ferment://wheel?id=')) {
      const id = trimmed.replace('ferment://wheel?id=', '').split('&')[0].trim();
      return { type: 'wheel', id, raw: trimmed };
    }
    if (trimmed.startsWith('ferment://recipe?data=')) {
      const recipeData = trimmed.replace('ferment://recipe?data=', '').split('&')[0].trim();
      return { type: 'recipe', recipeData, raw: trimmed };
    }
    if (trimmed.startsWith('ferment://recipe/')) {
      const id = trimmed.replace('ferment://recipe/', '').split('?')[0].trim();
      return { type: 'recipe', id, raw: trimmed };
    }
  }

  // 2. Try JSON payload (generated by A4 label sheets or external systems)
  if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
    try {
      const parsed = JSON.parse(trimmed);
      if (parsed.wheelId) {
        return { type: 'wheel', id: String(parsed.wheelId), raw: trimmed };
      }
      if (parsed.wheelTag) {
        return { type: 'wheel', id: String(parsed.wheelTag), raw: trimmed };
      }
      if (parsed.batchId) {
        return { type: 'batch', id: String(parsed.batchId), raw: trimmed };
      }
      if (parsed.batch) {
        return { type: 'batch', id: String(parsed.batch), raw: trimmed };
      }
      if (parsed.id) {
        const idStr = String(parsed.id);
        if (idStr.startsWith('wheel_') || idStr.startsWith('W-')) {
          return { type: 'wheel', id: idStr, raw: trimmed };
        }
        return { type: 'batch', id: idStr, raw: trimmed };
      }
    } catch {
      // Fall through to plain text parsing
    }
  }

  // 3. Plain ID prefixes
  if (trimmed.startsWith('wheel_') || /^W-\d+/i.test(trimmed)) {
    return { type: 'wheel', id: trimmed, raw: trimmed };
  }
  if (trimmed.startsWith('batch_') || /^BATCH-/i.test(trimmed)) {
    return { type: 'batch', id: trimmed, raw: trimmed };
  }

  return { type: 'unknown', id: trimmed, raw: trimmed };
}
